import { chromium } from "@playwright/test";
import { writeFileSync } from "node:fs";
const outDir = "uat/runs/undefined/shots/";
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 1400 } });
await page.goto("http://localhost:3000/org/vercel", { waitUntil: "domcontentloaded", timeout: 60000 });
await page.waitForTimeout(400);
const t0 = Date.now();
await page.getByRole("button", { name: /^Intel/ }).first().click({ timeout: 3000 });
await page.waitForTimeout(250);
const link = page.locator('nav[aria-label="Organization sections"] a[href="/org/vercel/teams"]');
await link.click({ timeout: 5000 });
await page.waitForLoadState("domcontentloaded", { timeout: 15000 }).catch(() => {});
await page.waitForLoadState("networkidle", { timeout: 8000 }).catch(() => {});
await page.waitForTimeout(300);
const t1 = Date.now();
console.log(`CLICK(expand Intel + click Teams)-TO-TEAMS latency: ${t1 - t0}ms; URL: ${page.url()}`);
await page.screenshot({ path: `${outDir}07-teams-page.png`, fullPage: true });
writeFileSync(`${outDir}07-teams-page.text.txt`, (await page.locator("body").innerText()).slice(0, 15000));
writeFileSync(`${outDir}07-teams-page.aria.yaml`, await page.locator("body").ariaSnapshot());
await browser.close();
